import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import { commandDefinitions } from "../shared/skill/scripts/lib/cli-command-registry.mjs";
import {
  localizedCommandHelpText,
  localizedRootHelpText
} from "../shared/skill/scripts/lib/localized-cli-help.mjs";
import { localizedCommandDefinition } from "../shared/skill/scripts/lib/runtime-locale.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const referencePath = path.join(root, "docs/cli-reference.md");

const untranslatedSummary = "（英語のみ）";

function tableCell(value) {
  return value.replace(/\|/gu, "\\|").replace(/\n/gu, " ");
}

function textBlock(value) {
  return ["```text", value, "```"].join("\n");
}

export function renderCliReference() {
  const names = [...commandDefinitions.keys()];
  const rows = names.map((name) => {
    const definition = commandDefinitions.get(name);
    const english = localizedCommandDefinition(definition, "en").summary;
    const japanese = localizedCommandDefinition(definition, "ja").summary;
    const japaneseCell = japanese === english ? untranslatedSummary : tableCell(japanese);
    return `| [\`${name}\`](#${name}) | ${tableCell(english)} | ${japaneseCell} |`;
  });

  const sections = names.flatMap((name) => [
    `## \`${name}\``,
    "",
    "### English",
    "",
    textBlock(localizedCommandHelpText(name, "en")),
    "",
    "### 日本語",
    "",
    textBlock(localizedCommandHelpText(name, "ja")),
    ""
  ]);

  return [
    "<!-- AUTO-GENERATED by scripts/build-cli-reference.mjs from the CLI command registry. Do not edit by hand. -->",
    "",
    "# CLI reference / CLIリファレンス",
    "",
    "This page is generated from the same command registry that prints `accessibility-audit --help`. Regenerate it with `node scripts/build-cli-reference.mjs --write` after changing a command.",
    "The Japanese blocks are the actual `--locale ja` output. Text without a Japanese translation stays in English, as it does in the CLI.",
    "このページは、`accessibility-audit --help`と同じコマンド定義から生成しています。コマンドを変更したら`node scripts/build-cli-reference.mjs --write`で再生成してください。",
    "日本語版は`--locale ja`の実際の出力です。日本語訳がない説明は、CLIと同じく英語のまま表示します。",
    "",
    "## Commands / コマンド一覧",
    "",
    "| Command / コマンド | Summary | 概要 |",
    "| --- | --- | --- |",
    ...rows,
    "",
    "## Global help / 全体のヘルプ",
    "",
    "### English",
    "",
    textBlock(localizedRootHelpText("en")),
    "",
    "### 日本語",
    "",
    textBlock(localizedRootHelpText("ja")),
    "",
    ...sections
  ].join("\n");
}

function normalize(text) {
  return text.replace(/\r\n/gu, "\n");
}

function main(argv) {
  if (argv.length !== 1 || !["--check", "--write"].includes(argv[0])) {
    process.stderr.write("Usage: node scripts/build-cli-reference.mjs --check|--write\n");
    return 2;
  }
  const expected = renderCliReference();
  const relative = path.relative(root, referencePath).split(path.sep).join("/");
  if (argv[0] === "--write") {
    fs.writeFileSync(referencePath, expected, "utf8");
    console.log(JSON.stringify({ status: "PASS", mode: "write", output: relative, commands: commandDefinitions.size }));
    return 0;
  }
  const current = fs.existsSync(referencePath) ? normalize(fs.readFileSync(referencePath, "utf8")) : null;
  if (current !== expected) {
    process.stderr.write(`${relative} is out of date. Run: node scripts/build-cli-reference.mjs --write\n`);
    return 1;
  }
  console.log(JSON.stringify({ status: "PASS", mode: "check", output: relative, commands: commandDefinitions.size }));
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
